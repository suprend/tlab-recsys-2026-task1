"""Three invented rows; independent typed9 order and canonical-byte oracle."""

import csv
from datetime import datetime
from decimal import Decimal
import gzip
import hashlib
import io
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch


class IndependentSourceOrder(unittest.TestCase):
    @patch.dict("sys.modules", {"catboost": None, "tsfresh": None})
    def test_import_archive_preserves_literal_typed9_order_and_canonical_bytes(self):
        import duckdb
        from scripts import source_import

        # Input and expectations spell the contract independently of production
        # FIELDS/TYPES/NULLABLE/ACTIONS and the existing test's CSV helper.
        rows = [
            [
                "2019-10-01 00:00:00 UTC", "view", "1152921504606846977",
                "2233445566778899001", "category-A,é", 'brand-A "quoted"',
                "12.30", "3344556677889900112", "session-A\nline",
            ],
            [
                "2019-10-17 12:34:56 UTC", "cart", "-101", "-202", "NULL",
                "", "-0.01", "-303", "session-B,雪",
            ],
            [
                "2019-10-31 23:59:59 UTC", "purchase", "", "", "",
                'brand-C\nline "quoted" é', "", "", "",
            ],
        ]
        stream = io.StringIO(newline="")
        writer = csv.writer(
            stream, delimiter=",", quotechar='"', doublequote=True,
            quoting=csv.QUOTE_MINIMAL, lineterminator="\n",
        )
        writer.writerow([
            "event_time", "event_type", "product_id", "category_id",
            "category_code", "brand", "price", "user_id", "user_session",
        ])
        writer.writerows(rows)
        raw = stream.getvalue().encode("utf-8")
        compressed = gzip.compress(raw, mtime=0)
        profile = {
            "version": 1,
            "scope": "synthetic_typed9_import_fixture",
            "compressed_sha256": hashlib.sha256(compressed).hexdigest(),
            "compressed_bytes": len(compressed),
            "uncompressed_bytes": len(raw),
            "expected_rows": 3,
            "fields": [
                "event_time", "event_type", "product_id", "category_id",
                "category_code", "brand", "price", "user_id", "user_session",
            ],
            "types": [
                "TIMESTAMP", "VARCHAR", "BIGINT", "BIGINT", "VARCHAR",
                "VARCHAR", "DECIMAL(12,2)", "BIGINT", "VARCHAR",
            ],
            "nullable_fields": [
                "product_id", "category_id", "category_code", "brand",
                "price", "user_id", "user_session",
            ],
            "start": "2019-10-01T00:00:00Z",
            "end": "2019-11-01T00:00:00Z",
            "actions": ["view", "cart", "purchase"],
            "compression": "gzip_all_members",
            "encoding": "utf-8-strict",
            "empty_policy": "unquoted_and_quoted_empty_to_NULL_only_declared_nullable",
            "max_field_characters": 65536,
        }
        # Literal UTF-8 bytes: é = c3 a9, 雪 = e9 9b aa. These are not
        # generated by the writer or any production schema/order helper.
        expected_csv = (
            b'"event_time","event_type","product_id","category_id",'
            b'"category_code","brand","price","user_id","user_session"\n'
            b'"2019-10-01 00:00:00 UTC","view","1152921504606846977",'
            b'"2233445566778899001","category-A,\xc3\xa9","brand-A ""quoted""",'
            b'"12.30","3344556677889900112","session-A\nline"\n'
            b'"2019-10-17 12:34:56 UTC","cart","-101","-202","NULL","",'
            b'"-0.01","-303","session-B,\xe9\x9b\xaa"\n'
            b'"2019-10-31 23:59:59 UTC","purchase","","","",'
            b'"brand-C\nline ""quoted"" \xc3\xa9","","",""\n'
        )

        with tempfile.TemporaryDirectory(prefix="source-order-") as directory:
            root = Path(directory).resolve()
            archive = root / "invented.csv.gz"
            work = root / "import"
            archive.write_bytes(compressed)
            result = source_import.import_archive(
                archive, work, profile, check=lambda: None,
            )

            # The implementation's actual canonical stream is validated.csv.
            self.assertEqual((work / "validated.csv").read_bytes(), expected_csv)
            self.assertEqual(result["validated_csv"], {
                "sha256": hashlib.sha256(expected_csv).hexdigest(),
                "bytes": len(expected_csv),
                "quoting": "all_fields",
                "parser": "Python_csv_strict",
                "native_reader_used": True,
            })
            self.assertEqual(result["schema"], [
                {"name": "event_time", "type": "TIMESTAMP"},
                {"name": "event_type", "type": "VARCHAR"},
                {"name": "product_id", "type": "BIGINT"},
                {"name": "category_id", "type": "BIGINT"},
                {"name": "category_code", "type": "VARCHAR"},
                {"name": "brand", "type": "VARCHAR"},
                {"name": "price", "type": "DECIMAL(12,2)"},
                {"name": "user_id", "type": "BIGINT"},
                {"name": "user_session", "type": "VARCHAR"},
            ])
            self.assertEqual(result["database"]["path"], str(work / "events.duckdb"))
            connection = duckdb.connect(str(work / "events.duckdb"), read_only=True)
            try:
                self.assertEqual(
                    [tuple(row[:2]) for row in connection.execute("DESCRIBE events").fetchall()],
                    [
                        ("event_time", "TIMESTAMP"), ("event_type", "VARCHAR"),
                        ("product_id", "BIGINT"), ("category_id", "BIGINT"),
                        ("category_code", "VARCHAR"), ("brand", "VARCHAR"),
                        ("price", "DECIMAL(12,2)"), ("user_id", "BIGINT"),
                        ("user_session", "VARCHAR"),
                    ],
                )
                self.assertEqual(
                    connection.execute(
                        "SELECT event_time, event_type, product_id, category_id, "
                        "category_code, brand, price, user_id, user_session "
                        "FROM events ORDER BY event_time"
                    ).fetchall(),
                    [
                        (
                            datetime(2019, 10, 1, 0, 0, 0), "view",
                            1152921504606846977, 2233445566778899001,
                            "category-A,é", 'brand-A "quoted"', Decimal("12.30"),
                            3344556677889900112, "session-A\nline",
                        ),
                        (
                            datetime(2019, 10, 17, 12, 34, 56), "cart", -101,
                            -202, "NULL", None, Decimal("-0.01"), -303,
                            "session-B,雪",
                        ),
                        (
                            datetime(2019, 10, 31, 23, 59, 59), "purchase",
                            None, None, None, 'brand-C\nline "quoted" é', None,
                            None, None,
                        ),
                    ],
                )
            finally:
                connection.close()
